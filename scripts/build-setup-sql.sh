#!/usr/bin/env bash
# Concatenates all migrations + seed into supabase/setup.sql, so a fresh project can be
# set up by pasting ONE file into Supabase → SQL Editor. Re-run after adding a migration.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup.sql
{
  echo "-- Tranquil Rest PMS: complete database setup for a NEW Supabase project."
  echo "-- Paste into Supabase → SQL Editor → Run. Generated by scripts/build-setup-sql.sh; do not edit by hand."
  echo "-- Contents: $(ls supabase/migrations/*.sql | xargs -n1 basename | tr '\n' ' ')+ seed.sql"
  echo
  for f in supabase/migrations/*.sql supabase/seed.sql; do
    echo "-- ============================================================================"
    echo "-- $(basename "$f")"
    echo "-- ============================================================================"
    cat "$f"
    echo
  done
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
